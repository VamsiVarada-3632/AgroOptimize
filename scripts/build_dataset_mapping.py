def build() -> dict:
    reg = {p["name"]: p for p in svc.provenance()}
    out = {"_note": "Generated by scripts/build_dataset_mapping.py from dataset_registry. Official datasets are the only runtime data source; "
                    "legacy/ synthetic CSVs are never read at runtime.", "datasets": {}, "disabled_features": DISABLED_FEATURES}
    for key, m in MAPPING.items():
        r = reg.get(m["dataset"])
        if r is None:
            raise SystemExit(f"dataset {m['dataset']} is not in dataset_registry - run scripts/preprocess_all.py first")
        out["datasets"][key] = {"source": m["source"], "file": r["filename"], "dataset": m["dataset"], "report_year": r["report_year"],
                                "rows": r["rows_clean"], "sha256": r["sha256"], "provides": m["provides"], "used_by": m["used_by"]}
    return out


if __name__ == "__main__":
    path = ROOT / "official_dataset_mapping.json"
    path.write_text(json.dumps(build(), indent=2, ensure_ascii=False) + "\n")
    print("wrote", path)
